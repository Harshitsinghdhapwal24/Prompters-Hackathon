import { jsPDF } from 'jspdf';
import { Lecture } from '@/types/lecture';

export function exportLectureToPdf(lecture: Lecture): void {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4',
  });

  const pageWidth = doc.internal.pageSize.getWidth();
  const pageHeight = doc.internal.pageSize.getHeight();
  const margin = 18;
  const contentWidth = pageWidth - margin * 2;
  let cursorY = margin;

  function checkPageBreak(requiredHeight: number) {
    if (cursorY + requiredHeight > pageHeight - margin - 10) {
      addFooter();
      doc.addPage();
      cursorY = margin;
      addRunningHeader();
    }
  }

  function addFooter() {
    const pageCount = (doc.internal as any).getNumberOfPages();
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(8);
    doc.setTextColor(140, 140, 150);
    doc.text(
      `Generated by LectureLens • Page ${pageCount}`,
      pageWidth / 2,
      pageHeight - 8,
      { align: 'center' }
    );
  }

  function addRunningHeader() {
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(8);
    doc.setTextColor(120, 120, 130);
    doc.text(lecture.title.slice(0, 50) + (lecture.title.length > 50 ? '...' : ''), margin, margin - 6);
    doc.setDrawColor(220, 220, 230);
    doc.setLineWidth(0.3);
    doc.line(margin, margin - 4, pageWidth - margin, margin - 4);
    cursorY = margin;
  }

  // --- Title & Metadata Banner ---
  doc.setFillColor(124, 58, 237); // Primary purple
  doc.roundedRect(margin, cursorY, contentWidth, 24, 3, 3, 'F');

  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(255, 255, 255);
  doc.text('LECTURELENS STUDY GUIDE', margin + 6, cursorY + 9);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(230, 220, 255);
  doc.text(
    `${lecture.subject.toUpperCase()} • ${lecture.durationMinutes || 45} MINS • ${new Date(lecture.createdAt).toLocaleDateString()}`,
    margin + 6,
    cursorY + 17
  );

  cursorY += 32;

  // Lecture Title
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(20, 24, 36);
  const titleLines = doc.splitTextToSize(lecture.title, contentWidth);
  checkPageBreak(titleLines.length * 7 + 6);
  doc.text(titleLines, margin, cursorY);
  cursorY += titleLines.length * 7 + 4;

  // Divider
  doc.setDrawColor(220, 225, 235);
  doc.setLineWidth(0.5);
  doc.line(margin, cursorY, pageWidth - margin, cursorY);
  cursorY += 8;

  // --- 1. Executive Summary & TL;DR ---
  checkPageBreak(30);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(12);
  doc.setTextColor(109, 40, 217); // Purple-700
  doc.text('1. Executive Summary (TL;DR)', margin, cursorY);
  cursorY += 6;

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(10);
  doc.setTextColor(50, 55, 65);
  const tldrLines = doc.splitTextToSize(lecture.summary.tldr, contentWidth);
  checkPageBreak(tldrLines.length * 5 + 4);
  doc.text(tldrLines, margin, cursorY);
  cursorY += tldrLines.length * 5 + 8;

  // Key Takeaways
  if (lecture.summary.keyTakeaways && lecture.summary.keyTakeaways.length > 0) {
    checkPageBreak(20);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(10.5);
    doc.setTextColor(30, 35, 45);
    doc.text('Key Takeaways:', margin, cursorY);
    cursorY += 5;

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(9.5);
    doc.setTextColor(60, 65, 75);

    lecture.summary.keyTakeaways.forEach((takeaway) => {
      const bulletLines = doc.splitTextToSize(`•  ${takeaway}`, contentWidth - 4);
      checkPageBreak(bulletLines.length * 5 + 2);
      doc.text(bulletLines, margin + 4, cursorY);
      cursorY += bulletLines.length * 5 + 2;
    });
    cursorY += 6;
  }

  // --- 2. Key Concepts & Definitions ---
  if (lecture.keyConcepts && lecture.keyConcepts.length > 0) {
    checkPageBreak(25);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(109, 40, 217);
    doc.text('2. Key Concepts & Definitions', margin, cursorY);
    cursorY += 6;

    lecture.keyConcepts.forEach((kc) => {
      checkPageBreak(20);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10);
      doc.setTextColor(20, 25, 35);
      doc.text(`${kc.term} [${kc.importance.toUpperCase()} PRIORITY]`, margin, cursorY);
      cursorY += 4.5;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9);
      doc.setTextColor(65, 70, 80);
      const defLines = doc.splitTextToSize(kc.definition, contentWidth - 4);
      checkPageBreak(defLines.length * 4.5 + 4);
      doc.text(defLines, margin + 4, cursorY);
      cursorY += defLines.length * 4.5 + 4;
    });
    cursorY += 4;
  }

  // --- 3. Important Formulas ---
  if (lecture.formulas && lecture.formulas.length > 0) {
    checkPageBreak(25);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(109, 40, 217);
    doc.text('3. Governing Formulas & Mathematics', margin, cursorY);
    cursorY += 6;

    lecture.formulas.forEach((f) => {
      checkPageBreak(22);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(10);
      doc.setTextColor(30, 35, 45);
      doc.text(f.name, margin, cursorY);
      cursorY += 4.5;

      doc.setFont('courier', 'bold');
      doc.setFontSize(9.5);
      doc.setTextColor(109, 40, 217);
      const formulaLines = doc.splitTextToSize(f.formula, contentWidth - 4);
      doc.text(formulaLines, margin + 4, cursorY);
      cursorY += formulaLines.length * 5 + 3;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(8.5);
      doc.setTextColor(80, 85, 95);
      const descLines = doc.splitTextToSize(f.description, contentWidth - 4);
      checkPageBreak(descLines.length * 4 + 4);
      doc.text(descLines, margin + 4, cursorY);
      cursorY += descLines.length * 4 + 4;
    });
    cursorY += 4;
  }

  // --- 4. High-Yield Practice Quiz Questions ---
  if (lecture.quiz && lecture.quiz.length > 0) {
    checkPageBreak(30);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(12);
    doc.setTextColor(109, 40, 217);
    doc.text('4. High-Yield Practice Quiz Questions', margin, cursorY);
    cursorY += 6;

    lecture.quiz.forEach((q, idx) => {
      checkPageBreak(30);
      doc.setFont('helvetica', 'bold');
      doc.setFontSize(9.5);
      doc.setTextColor(20, 25, 35);
      const qLines = doc.splitTextToSize(`Q${idx + 1}: ${q.question}`, contentWidth);
      doc.text(qLines, margin, cursorY);
      cursorY += qLines.length * 5 + 3;

      doc.setFont('helvetica', 'normal');
      doc.setFontSize(9);
      doc.setTextColor(70, 75, 85);

      q.options.forEach((opt, optIdx) => {
        const isCorrect = optIdx === q.correctAnswerIndex;
        const prefix = isCorrect ? '✓ ' : '   ';
        const optLines = doc.splitTextToSize(`${prefix}${String.fromCharCode(65 + optIdx)}) ${opt}`, contentWidth - 6);
        if (isCorrect) {
          doc.setFont('helvetica', 'bold');
          doc.setTextColor(22, 101, 52); // green
        } else {
          doc.setFont('helvetica', 'normal');
          doc.setTextColor(70, 75, 85);
        }
        checkPageBreak(optLines.length * 4.5);
        doc.text(optLines, margin + 6, cursorY);
        cursorY += optLines.length * 4.5;
      });

      // Explanation
      doc.setFont('helvetica', 'italic');
      doc.setFontSize(8.5);
      doc.setTextColor(100, 105, 115);
      const expLines = doc.splitTextToSize(`Explanation: ${q.explanation}`, contentWidth - 6);
      checkPageBreak(expLines.length * 4 + 4);
      doc.text(expLines, margin + 6, cursorY + 2);
      cursorY += expLines.length * 4 + 6;
    });
  }

  // Add final footer
  addFooter();

  // Save PDF to browser download
  const cleanTitle = lecture.title
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '_')
    .slice(0, 30);
  doc.save(`lecturelens_${cleanTitle}_notes.pdf`);
}
